--[[
  lib/clipboard.lua — copy text to the clipboard

  The Lightroom SDK has no documented clipboard module, so this mirrors the approach
  of the in-house plugin: try LrClipboard if a build exposes it, otherwise hand the
  text to macOS pbcopy through a temp file (LrTasks.execute; the command line carries
  no user text). If both fail the caller shows the text in a selectable field.

  Must run inside an async task (LrTasks.execute yields) and not inside pcall.
]]

local LrFileUtils = import 'LrFileUtils'
local LrPathUtils = import 'LrPathUtils'
local LrTasks = import 'LrTasks'

local ids = dofile(_PLUGIN.path .. '/lib/ids.lua')
local log = dofile(_PLUGIN.path .. '/lib/log.lua')

local M = {}

local function tryLrClipboard(value)
  local okImport, mod = pcall(import, 'LrClipboard')
  if not okImport or type(mod) ~= 'table' or type(mod.setContents) ~= 'function' then
    return false
  end
  local okSet = pcall(mod.setContents, value)
  return okSet
end

--- @return boolean copied
function M.copy(value)
  if type(value) ~= 'string' or value == '' then return false end

  if tryLrClipboard(value) then
    log.info('clipboard: LrClipboard')
    return true
  end

  if MAC_ENV ~= true then
    log.info('clipboard: no method available on this platform')
    return false
  end

  local tmp = LrPathUtils.child(LrPathUtils.getStandardFilePath('temp'), 'papat-clip-' .. ids.uuid() .. '.txt')
  local fh = io.open(tmp, 'wb')
  if not fh then return false end
  fh:write(value)
  fh:close()

  -- tmp is generated by us (temp dir + uuid): no quote characters possible.
  local rc = LrTasks.execute("LANG=en_US.UTF-8 /usr/bin/pbcopy < '" .. tmp .. "'")
  LrFileUtils.delete(tmp)
  log.info('clipboard: pbcopy rc=%s', tostring(rc))
  return rc == 0
end

return M
